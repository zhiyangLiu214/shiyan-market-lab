const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync('static/terminal.js', 'utf8');
const context = vm.createContext({});
vm.runInContext(source.slice(source.indexOf('const esc ='), source.indexOf('const factorNames =')), context);
assert.equal(vm.runInContext('money(null)', context), '—');
assert.equal(vm.runInContext('money(0)', context), '0.00 万');
assert.equal(vm.runInContext('money(-150000000)', context), '−1.50 亿');
const stock = {date: '2026-11-10', funds: {status: 'ok', date: '2026-11-10', net: 10, ratio: 1, positive_days: 1}};
context.stock = stock;
assert.match(vm.runInContext('fundsEvidence(stock)', context), /单日资金不代表持续流入/);
stock.funds.positive_days = 3;
assert.match(vm.runInContext('fundsEvidence(stock)', context), /最近 3 个交易日持续净流入/);
stock.funds.net = -10;
assert.match(vm.runInContext('fundsEvidence(stock)', context), /净流出/);
stock.funds.date = '2026-11-09';
assert.match(vm.runInContext('fundsEvidence(stock)', context), /日期未对齐/);
stock.funds.status = 'stale';
assert.match(vm.runInContext('fundsEvidence(stock)', context), /不作为当前信号依据/);
assert.doesNotMatch(vm.runInContext('fundsEvidence(stock)', context), /持续净流入/);
console.log('Fund display: units, signs, single-day/streak, mismatched date and stale evidence passed.');
